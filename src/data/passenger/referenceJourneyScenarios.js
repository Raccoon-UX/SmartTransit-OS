export function getReferenceScenariosByPattern(patternType) {
  if (!patternType || patternType === 'ALL') return REFERENCE_JOURNEY_SCENARIOS;
  return REFERENCE_JOURNEY_SCENARIOS.filter((s) => s.routingPatternType === patternType);
}

export function getReferenceScenarioById(scenarioId) {
  return REFERENCE_JOURNEY_SCENARIOS.find((s) => s.id === scenarioId || s.scenarioNumber === Number(scenarioId));
}

